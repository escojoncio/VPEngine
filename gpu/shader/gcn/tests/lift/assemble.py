#!/usr/bin/env python3
"""Assembles each NAME.s here into NAME.lift (header keys + hex words) with llvm-mc, the same
black-box oracle the decoder corpus uses. Run it after editing a .s file; the test reads .lift only.
.s format: '## key value' lines (stage, user_sgprs, ps_input_addr, lds_bytes), assembly, and
optionally '## fetch' followed by the fetch subroutine."""
import glob, os, shutil, subprocess, sys, tempfile

MC = ["llvm-mc", "-arch=amdgcn", "-mcpu=bonaire"]
OBJCOPY = shutil.which("llvm-objcopy") or "llvm-objcopy-18"


def words(lines):
    # An object file, not -show-encoding: branch offsets to labels are only resolved at layout.
    with tempfile.TemporaryDirectory() as tmp:
        obj, raw = os.path.join(tmp, "p.o"), os.path.join(tmp, "p.bin")
        out = subprocess.run(MC + ["-filetype=obj", "-o", obj], input="\n".join(lines) + "\n",
                             capture_output=True, text=True)
        if out.returncode or "error" in out.stderr:
            sys.exit(out.stderr)
        subprocess.run([OBJCOPY, "-O", "binary", "--only-section=.text", obj, raw], check=True)
        data = open(raw, "rb").read()
    return [int.from_bytes(data[j:j + 4], "little") for j in range(0, len(data), 4)]


here = os.path.dirname(os.path.abspath(__file__))
for path in sorted(glob.glob(os.path.join(here, "*.s"))):
    header, parts, cur = [], {"code": [], "fetch": []}, "code"
    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("## fetch"):
            cur = "fetch"
        elif line.startswith("## "):
            header.append(line[3:])
        elif line.strip() and not line.startswith("//"):
            parts[cur].append(line)
    with open(path[:-2] + ".lift", "w") as f:
        f.write("# generated by assemble.py from " + os.path.basename(path) + "\n")
        for h in header:
            f.write(h + "\n")
        for k in ("code", "fetch"):
            if parts[k]:
                f.write(k + " " + " ".join(f"{x:08x}" for x in words(parts[k])) + "\n")
    print("ok", os.path.basename(path))
