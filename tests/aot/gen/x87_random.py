#!/usr/bin/env python3
"""Generates tests/aot/cases/x87_random.s: a long random x87 program (fixed seed) over special
and ordinary values, every exact instruction, all precision/rounding controls; after every few
instructions the status word is stored, and at the end the whole stack, so that the differential
harness compares each intermediate result with the hardware.  usage: x87_random.py [seed] [count]"""
import random, struct, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1234
count = int(sys.argv[2]) if len(sys.argv) > 2 else 1500
rng = random.Random(seed)

def f80(sign, exp, mant): return (mant, (sign << 15) | exp)
specials80 = [
    f80(0, 0x3FFF, 1 << 63), f80(1, 0x3FFF, 1 << 63), f80(0, 0, 0), f80(1, 0, 0),
    f80(0, 0x7FFF, 1 << 63), f80(1, 0x7FFF, 1 << 63),                     # infinities
    f80(0, 0x7FFF, 0xC000000000000000), f80(1, 0x7FFF, 0xC000000000001234),  # quiet NaNs
    f80(0, 0x7FFF, 0x8000000000000001),                                   # signalling NaN
    f80(0, 0, 0x0000000000000123), f80(1, 0, 0x7FFFFFFFFFFFFFFF),         # denormals
    f80(0, 0x7FFE, 0xFFFFFFFFFFFFFFFF), f80(0, 1, 1 << 63),               # largest, smallest normal
]
vals80 = list(specials80)
for _ in range(60):
    e = rng.choice([rng.randint(0x3FF0, 0x400F), rng.randint(0x3F00, 0x40FF), rng.randint(1, 0x7FFE)])
    vals80.append(f80(rng.randint(0, 1), e, (1 << 63) | rng.getrandbits(63)))
f64s = [0.1, -2.5, 1e300, -1e-300, 3.0, 7.0, 0.5, 1e20, 123456.789, -0.0, float('inf'), float('nan'), 5e-324]
f32s = [1.5, -0.1, 3.4e38, 1e-40, 2.0, -7.25, float('inf'), 1e-10]
i16s = [0, 1, -1, 32767, -32768, 1234]
i32s = [0, 7, -7, 2147483647, -2147483648, 100000007]
i64s = [0, 3, -3, (1 << 63) - 1, -(1 << 63), 0x123456789ABCDEF]
cws = [0x037F, 0x007F, 0x027F, 0x077F, 0x0B7F, 0x0F7F, 0x0E7F, 0x047F, 0x087F, 0x0C7F, 0x0A7F, 0x067F]

out = []
emit = out.append
emit("# Generated by tests/aot/gen/x87_random.py (seed %d, %d steps): do not edit." % (seed, count))
emit(".text\n.globl _start\n_start:\n    mov $0x600000, %rdi\n    lea k(%rip), %rsi")
depth = 0
store = 0x100
def st_slot(n): 
    global store
    a = store; store += n
    if store > 0xF000: store = 0x100
    return a
def mem80(): return "%d(%%rsi)" % (16 * rng.randrange(len(vals80)))
off_f64 = 16 * len(vals80)
off_f32 = off_f64 + 8 * len(f64s)
off_i16 = off_f32 + 4 * len(f32s)
off_i32 = off_i16 + 2 * len(i16s)
off_i64 = off_i32 + 4 * len(i32s)
off_cw = off_i64 + 8 * len(i64s)
def memf64(): return "%d(%%rsi)" % (off_f64 + 8 * rng.randrange(len(f64s)))
def memf32(): return "%d(%%rsi)" % (off_f32 + 4 * rng.randrange(len(f32s)))
def memi16(): return "%d(%%rsi)" % (off_i16 + 2 * rng.randrange(len(i16s)))
def memi32(): return "%d(%%rsi)" % (off_i32 + 4 * rng.randrange(len(i32s)))
def memi64(): return "%d(%%rsi)" % (off_i64 + 8 * rng.randrange(len(i64s)))

for step in range(count):
    choice = rng.random()
    if depth < 2 or (choice < 0.25 and depth < 7):
        kind = rng.randrange(7)
        emit(["    fldt " + mem80(), "    fldl " + memf64(), "    flds " + memf32(), "    filds " + memi16(),
              "    fildl " + memi32(), "    fildll " + memi64(),
              "    " + rng.choice(["fld1", "fldz", "fldpi", "fldl2e", "fldl2t", "fldlg2", "fldln2"])][kind])
        depth += 1
        continue
    i = rng.randrange(1, depth)
    r = rng.random()
    if r < 0.30:
        op = rng.choice(["fadd", "fsub", "fsubr", "fmul", "fdiv", "fdivr"])
        form = rng.randrange(6)
        if form == 0: emit("    %s %%st(%d), %%st" % (op, i))
        elif form == 1: emit("    %s %%st, %%st(%d)" % (op, i))
        elif form == 2: emit("    %sp %%st, %%st(%d)" % (op, i)); depth -= 1
        elif form == 3: emit("    %sl %s" % (op, memf64()))
        elif form == 4: emit("    %ss %s" % (op, memf32()))
        else: emit("    fi%s%s %s" % (op[1:], rng.choice(["s", "l"]), memi16() if rng.random() < 0.5 else memi32()) if False else "    fi%sl %s" % (op[1:], memi32()))
    elif r < 0.38:
        emit("    " + rng.choice(["fsqrt", "frndint", "fchs", "fabs", "fxam", "ftst", "fprem", "fprem1", "fscale"]))
    elif r < 0.42:
        emit("    fxtract"); depth += 1
        if depth > 8: depth = 8
    elif r < 0.50:
        cmp = rng.choice(["fcom %%st(%d)" % i, "fucom %%st(%d)" % i, "fcoms " + memf32(), "fcoml " + memf64(), "ficoml " + memi32()])
        emit("    " + cmp)
    elif r < 0.56:
        op = rng.choice(["fcomi", "fucomi", "fcomip", "fucomip"])
        emit("    %s %%st(%d), %%st" % (op, i))
        emit("    setb %%al\n    setz %%cl\n    setp %%dl\n    mov %%al, %d(%%rdi)\n    mov %%cl, %d(%%rdi)\n    mov %%dl, %d(%%rdi)" % (st_slot(1), st_slot(1), st_slot(1)))
        if op.endswith("p"): depth -= 1
    elif r < 0.60:
        emit("    fxch %%st(%d)" % i)
    elif r < 0.64:
        cc = rng.choice(["fcmovb", "fcmove", "fcmovbe", "fcmovu", "fcmovnb", "fcmovne", "fcmovnbe", "fcmovnu"])
        emit("    " + rng.choice(["stc", "clc", "xor %eax, %eax", "mov $3, %eax\n    cmp $5, %eax", "mov $5, %eax\n    cmp $3, %eax",
                                    "mov $7, %eax\n    cmp $7, %eax"]))
        emit("    %s %%st(%d), %%st" % (cc, i))
    elif r < 0.75:
        st = rng.randrange(9)
        if st == 0: emit("    fstps %d(%%rdi)" % st_slot(4)); depth -= 1
        elif st == 1: emit("    fstpl %d(%%rdi)" % st_slot(8)); depth -= 1
        elif st == 2: emit("    fstpt %d(%%rdi)" % st_slot(10)); depth -= 1
        elif st == 3: emit("    fistps %d(%%rdi)" % st_slot(2)); depth -= 1
        elif st == 4: emit("    fistpl %d(%%rdi)" % st_slot(4)); depth -= 1
        elif st == 5: emit("    fistpll %d(%%rdi)" % st_slot(8)); depth -= 1
        elif st == 6: emit("    fisttpll %d(%%rdi)" % st_slot(8)); depth -= 1
        elif st == 7: emit("    fstl %d(%%rdi)" % st_slot(8))
        else: emit("    fstp %%st(%d)" % i); depth -= 1
    elif r < 0.80:
        emit("    fldcw %d(%%rsi)" % (off_cw + 2 * rng.randrange(len(cws))))
    elif r < 0.84:
        emit("    fnclex")
    else:
        emit("    fld %%st(%d)" % i); depth += 1
    if rng.random() < 0.35:
        emit("    fnstsw %d(%%rdi)" % st_slot(2))
    if depth > 8: depth = 8
    if depth < 0: depth = 0
emit("    fnstsw %d(%%rdi)" % st_slot(2))
emit("    ret")
emit(".section .rodata\n.balign 16\nk:")
for m, se in vals80: emit("    .quad 0x%016x\n    .short 0x%04x, 0, 0, 0" % (m, se))
for v in f64s: emit("    .quad 0x%016x" % struct.unpack("<Q", struct.pack("<d", v))[0])
for v in f32s: emit("    .long 0x%08x" % struct.unpack("<I", struct.pack("<f", v))[0])
for v in i16s: emit("    .short %d" % v)
for v in i32s: emit("    .long %d" % v)
for v in i64s: emit("    .quad %d" % v)
for v in cws: emit("    .short 0x%04x" % v)
open(__file__.replace("gen/x87_random.py", "cases/x87_random.s"), "w").write("\n".join(out) + "\n")
