// Differential test of the GCN lifter: each program of programs.txt runs on the reference
// interpreter (one 64-lane wave, gcn_ref) and, lifted to VPIR, on the VPIR interpreter (64
// invocations, one per lane). Every exported component must match bit for bit (any NaN equals any
// NaN). Prints the first mismatches with the program's source.
//
// usage: vpgcn_diff programs.txt [--verbose | --emit-msl DIR]
// --emit-msl also writes each lifted program's MSL to DIR/p<index>.metal (CI compiles them with
// the headset's Metal compiler: the emitter on random op combinations).
// Debugging one program: VPGCN_DIFF_PRINT=<index> prints its VPIR and every lane's exports (reference
// and lifted); VPGCN_DIFF_TRACE_LANE=<lane> also traces that lane's evaluation to stderr.
#include <cmath>
#include <cstdio>
#include <cstring>
#include <fstream>
#include <map>
#include <random>
#include <sstream>
#include <string>
#include <vector>

#include "../ref/gcn_ref.h"
#include "vpgcn/gcn.h"
#include "vpgcn/lift.h"
#include "vpir_eval.h"
#include "vpir/text.h"
#include "vpmsl/msl.h"
#include <cstdlib>

namespace {

struct Program {
    std::vector<std::string> source;
    std::vector<uint32_t> words;
};

// Bit-exact, except that any NaN equals any NaN and +0 equals -0 (the sign of a zero is
// unobservable but for 1/x, and the GPUs' min/max/med3 differ on it).
bool sameBits(uint32_t a, uint32_t b) {
    if (a == b) return true;
    if ((a | b) == 0x80000000u) return true;
    float fa, fb;
    std::memcpy(&fa, &a, 4);
    std::memcpy(&fb, &b, 4);
    return std::isnan(fa) && std::isnan(fb);
}

}  // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::fprintf(stderr, "usage: vpgcn_diff programs.txt [--verbose]\n");
        return 2;
    }
    bool verbose = argc > 2 && std::string(argv[2]) == "--verbose";
    std::string mslDir = argc > 3 && std::string(argv[2]) == "--emit-msl" ? argv[3] : "";
    std::ifstream in(argv[1]);
    std::vector<Program> programs;
    std::vector<std::string> pending;
    for (std::string line; std::getline(in, line);) {
        if (line.rfind("# ", 0) == 0 && line.find("generated by") == std::string::npos) pending.push_back(line.substr(2));
        if (line.rfind("prog ", 0) == 0) {
            Program p;
            p.source = pending;
            pending.clear();
            std::istringstream ss(line.substr(5));
            for (std::string w; ss >> w;) p.words.push_back(uint32_t(std::stoul(w, nullptr, 16)));
            programs.push_back(p);
        }
    }
    std::mt19937 rng(7);
    unsigned ok = 0, failed = 0, refUnsupported = 0, liftFailed = 0, evalFailed = 0, shown = 0;
    std::map<std::string, unsigned> unsupported;
    for (size_t pi = 0; pi < programs.size(); ++pi) {
        const Program& p = programs[pi];
        // User data: integers, small values and floats.
        uint32_t ud[16];
        for (unsigned k = 0; k < 16; ++k) {
            unsigned kind = rng() % 4;
            float fv = float(int(rng() % 2001) - 1000) / 37.0f;
            ud[k] = kind == 0 ? rng() : kind == 1 ? rng() % 64 : kind == 2 ? std::bit_cast<uint32_t>(fv) : uint32_t(-int(rng() % 9));
        }
        // Reference.
        vpgcnref::Wave w{};
        for (unsigned k = 0; k < 16; ++k) w.s[k] = ud[k];
        for (unsigned lane = 0; lane < 64; ++lane) w.v[0][lane] = lane;
        w.exec = ~0ull;
        std::map<unsigned, std::vector<std::array<uint32_t, 4>>> refExports;  // param -> lane values
        bool refOk = true;
        std::string err;
        unsigned steps = 0;
        for (size_t pc = 0; pc < p.words.size();) {
            vpgcn::Instruction x;
            if (!vpgcn::decode(std::span(p.words).subspan(pc), x)) {
                refOk = false;
                err = "undecodable";
                break;
            }
            pc += x.size / 4;
            if (x.op == vpgcn::Op::s_endpgm) break;
            if (++steps > 200000) {
                refOk = false;
                err = "runs too long";
                break;
            }
            // Wave-level branches (the reference steps one instruction; control flow is here).
            {
                using vpgcn::Op;
                bool branch = true, taken = false;
                switch (x.op) {
                    case Op::s_branch: taken = true; break;
                    case Op::s_cbranch_scc0: taken = !w.scc; break;
                    case Op::s_cbranch_scc1: taken = w.scc; break;
                    case Op::s_cbranch_vccz: taken = w.vcc == 0; break;
                    case Op::s_cbranch_vccnz: taken = w.vcc != 0; break;
                    case Op::s_cbranch_execz: taken = w.exec == 0; break;
                    case Op::s_cbranch_execnz: taken = w.exec != 0; break;
                    default: branch = false; break;
                }
                if (branch) {
                    if (taken) pc = size_t(int64_t(pc) + int16_t(x.simm16));
                    continue;
                }
            }
            if (x.encoding == vpgcn::Encoding::EXP && (x.mem.target < 32 || x.mem.target >= 64)) continue;  // (pos)
            if (x.encoding == vpgcn::Encoding::EXP) {
                std::vector<std::array<uint32_t, 4>> lanes(64);
                for (unsigned lane = 0; lane < 64; ++lane)
                    for (unsigned c = 0; c < 4; ++c)
                        lanes[lane][c] = x.src[c].kind == vpgcn::OperandKind::Vgpr ? w.v[x.src[c].index][lane] : 0;
                refExports[x.mem.target - 32] = lanes;
                continue;
            }
            if (!vpgcnref::step(x, w, err)) {
                refOk = false;
                break;
            }
        }
        if (!refOk) {
            ++refUnsupported;
            ++unsupported[err];
            continue;
        }
        // Lifted.
        vpgcn::LiftInput li;
        li.stage = vpgcn::ShaderStage::Vertex;
        li.userSgprs = 16;
        li.vgprCompCnt = 0;
        li.code = p.words;
        vpgcn::LiftResult r = vpgcn::lift(li);
        if (!r.errors.empty()) {
            ++liftFailed;
            if (verbose) std::printf("program %zu: lift error %s\n", pi, r.errors.front().c_str());
            continue;
        }
        if (!mslDir.empty()) {
            vpmsl::EmitResult em = vpmsl::emitMsl(r.module);
            if (!em.errors.empty()) {
                std::printf("program %zu: MSL emit error %s\n", pi, em.errors.front().c_str());
                ++liftFailed;
                continue;
            }
            std::ofstream(mslDir + "/p" + std::to_string(pi) + ".metal") << em.shader.source;
        }
        const char* printEnv = std::getenv("VPGCN_DIFF_PRINT");
        bool printThis = printEnv && std::stoul(printEnv) == pi;
        if (printThis) std::printf("%s\n", vpir::print(r.module).c_str());
        std::vector<uint8_t> udBytes(64);
        std::memcpy(udBytes.data(), ud, 64);
        bool mismatch = false, evalOk = true;
        for (unsigned lane = 0; lane < 64 && !mismatch && evalOk; ++lane) {
            vpireval::Invocation inv;
            vpireval::Value vid;
            vid.type = vpir::kU32;
            vid.bits[0] = lane;
            inv.builtins[vpir::Builtin::VertexId] = vid;
            if (r.userDataSlot) inv.memory[*r.userDataSlot] = udBytes;
            std::string e;
            const char* traceLane = std::getenv("VPGCN_DIFF_TRACE_LANE");
            vpireval::trace = printThis && traceLane && std::stoul(traceLane) == lane;
            if (!vpireval::run(r.module, inv, e)) {
                evalOk = false;
                if (verbose) std::printf("program %zu: eval error %s\n", pi, e.c_str());
                break;
            }
            if (printThis)
                for (auto& [param, lanes] : refExports)
                    for (auto& [idx, val] : inv.outputs)
                        if (r.module.outputs[idx].builtin == vpir::Builtin::None && r.module.outputs[idx].location == param)
                            for (unsigned c = 0; c < 4; ++c)
                                std::printf("lane %u v%u ref 0x%08x lifted 0x%08x\n", lane, param * 4 + c,
                                            lanes[lane][c], val.bits[c]);
            for (auto& [param, lanes] : refExports) {
                const vpireval::Value* got = nullptr;
                for (auto& [idx, val] : inv.outputs)
                    if (r.module.outputs[idx].builtin == vpir::Builtin::None && r.module.outputs[idx].location == param)
                        got = &val;
                for (unsigned c = 0; c < 4; ++c) {
                    uint32_t want = lanes[lane][c], have = got ? got->bits[c] : 0xdeadbeef;
                    if (sameBits(want, have)) continue;
                    mismatch = true;
                    {
                        // The last body instruction writing that register (v12-15/v20-23 hold s16-23).
                        unsigned reg = param * 4 + c;
                        std::string name = reg >= 12 && reg <= 15 ? "s" + std::to_string(16 + reg - 12)
                                         : reg >= 20 ? "s" + std::to_string(20 + reg - 20)
                                         : reg == 16 ? "exec" : reg == 17 ? "vcc" : reg == 18 ? "s[24:25]"
                                         : reg == 19 ? "s[26:27]" : "v" + std::to_string(reg);
                        std::string writer = "?";
                        for (const std::string& s2 : p.source) {
                            size_t sp = s2.find(' ');
                            if (sp == std::string::npos) continue;
                            std::string first = s2.substr(sp + 1, s2.find(',', sp) - sp - 1);
                            if (first == name) writer = s2;
                        }
                        std::printf("WRITER %s\n", writer.substr(0, writer.find(' ')).c_str());
                    }
                    if (shown++ < 400) {
                        std::printf("MISMATCH program %zu lane %u param%u.%c (v%u): reference 0x%08x, lifted 0x%08x\n", pi,
                                    lane, param, "xyzw"[c], param * 4 + c, want, have);
                        std::printf("  user data:");
                        for (unsigned k = 0; k < 16; ++k) std::printf(" s%u=0x%x", k, ud[k]);
                        std::printf("\n");
                        for (const std::string& s : p.source) std::printf("    %s\n", s.c_str());
                    }
                    break;
                }
                if (mismatch) break;
            }
        }
        if (!evalOk) ++evalFailed;
        else if (mismatch) ++failed;
        else ++ok;
    }
    std::printf("%zu programs: %u match, %u mismatch, %u lift errors, %u eval errors, %u not run (reference)\n",
                programs.size(), ok, failed, liftFailed, evalFailed, refUnsupported);
    for (auto& [e, n] : unsupported) std::printf("  reference: %u x %s\n", n, e.c_str());
    return failed || liftFailed || evalFailed ? 1 : 0;
}
